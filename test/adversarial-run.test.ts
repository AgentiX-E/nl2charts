/**
 * The adversarial harness, driven end to end on a dataset it has never seen.
 *
 * The case set in `cases.ts` is hand-written against BIRD's databases, which makes it a good
 * subject and a bad fixture: 30 cases over six databases, each worth a model call. So the
 * cases are an input here (`io.cases`) and these tests pass their own, against a temporary
 * database. What is under test is the harness — the gold checks, the width check, the arms,
 * the pairing, the refusal to publish — not the cases.
 *
 * Two defects are now tests rather than comments. The headline ablation used to compare the
 * `definitions` arm and label it `names -> metadata`, so the published number for the metadata
 * lever belonged to a different arm; and the inline arm's definitions were generated by the
 * model *before* the gold statements ran, which spent a call on a case set that could not run.
 */
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { afterAll, describe, expect, it } from 'vitest';
import { createHttpProvider } from '@agentix-e/nl2charts-ai';
import { MINI_DB, writeMiniBirdDataset } from './helpers/bird-dataset.js';
import { startEndpoint } from './helpers/endpoint.js';
import { createOracle } from '../eval/bird/oracle.js';
import {
  ablationFor,
  adversarialReport,
  armLines,
  armNamed,
  checkGold,
  declaredWidth,
  main,
  prepareAdversarial,
  resolveAdversarialSettings,
  runAdversarial,
  schemaForArm,
  writeAdversarialArtifact,
} from '../eval/adversarial/run.js';
import type { AdversarialCase } from '../eval/adversarial/run.js';

const root = mkdtempSync(join(tmpdir(), 'nl2charts-adversarial-'));
const data = writeMiniBirdDataset(join(root, 'MINIDEV'));
const oracle = createOracle(resolve('eval/bird/oracle.py'), join(data, 'dev_databases'));

afterAll(async () => {
  await oracle.close();
  rmSync(root, { recursive: true, force: true });
});

/** A case set small enough to read, on the one database the fixture ships. */
const CASES: readonly AdversarialCase[] = [
  {
    id: 'tie-1',
    category: 'tie',
    probes: 'the maximum is shared by two rows',
    db: MINI_DB,
    question: 'How many items are there?',
    sql: 'select count(*) from items',
  },
  {
    id: 'window-1',
    category: 'window',
    probes: 'a ranking that has to survive a tie',
    db: MINI_DB,
    question: 'List exactly two columns: the name of every item and its price.',
    sql: 'select name, price from items order by id limit 1',
  },
];

const GOLD: Record<string, string> = Object.fromEntries(CASES.map((entry) => [entry.question, entry.sql]));

function fenced(sql: string): string {
  return '```sql\n' + sql + '\n```';
}

/** The endpoint answers each question with its gold, and every other prompt with nonsense. */
function reply(prompt: string, correct: boolean): string {
  const question = Object.keys(GOLD).find((entry) => prompt.includes(entry));
  if (question === undefined) return '- items.price: the list price of one unit';
  return fenced(correct ? (GOLD[question] as string) : 'select 1');
}

const settings = (overrides: Record<string, string | undefined> = {}) =>
  resolveAdversarialSettings(
    { BIRD_DATA: data, BIRD_PROFILE_CACHE: join(root, 'profiles'), ADVERSARIAL_OUT: join(root, 'out.json'), ...overrides },
    [],
    root,
  );

describe('the width a question promises', () => {
  it('reads a word', () => {
    expect(declaredWidth('List exactly two columns: name and price')).toBe(2);
  });

  it('reads a digit, which the word table cannot', () => {
    // The table stops at four, so `exactly 5 columns` used to return undefined and skip the
    // check rather than fail it.
    expect(declaredWidth('Show exactly 5 columns')).toBe(5);
  });

  it('reports no promise when the question makes none', () => {
    expect(declaredWidth('How many items are there?')).toBeUndefined();
  });

  it('ignores a word that is not a number', () => {
    expect(declaredWidth('Show exactly several columns')).toBeUndefined();
  });
});

describe('settings', () => {
  it('defaults to the cached Mini-Dev split and the repository artifact', () => {
    const resolved = resolveAdversarialSettings({}, [], root);
    expect(resolved.data).toBe(join(root, 'eval/.cache/bird/minidev/MINIDEV'));
    expect(resolved.databases).toBe(join(root, 'eval/.cache/bird/minidev/MINIDEV/dev_databases'));
    expect(resolved.out).toBe(join(root, 'eval/out/adversarial.json'));
    expect(resolved.concurrency).toBe(6);
    expect(resolved.dryRun).toBe(false);
  });

  it('takes the dataset, the artifact and the dry run from the environment', () => {
    const resolved = resolveAdversarialSettings(
      { BIRD_DATA: data, ADVERSARIAL_OUT: '/tmp/a.json', BIRD_CONCURRENCY: '2', BIRD_DATABASES: '/tmp/dbs' },
      ['--dry-run'],
      root,
    );
    expect(resolved.data).toBe(data);
    expect(resolved.out).toBe('/tmp/a.json');
    expect(resolved.concurrency).toBe(2);
    expect(resolved.databases).toBe('/tmp/dbs');
    expect(resolved.dryRun).toBe(true);
  });

  it('refuses a concurrency that is not a positive integer', () => {
    expect(() => resolveAdversarialSettings({ BIRD_CONCURRENCY: 'lots' }, [], root)).toThrow(/BIRD_CONCURRENCY/);
  });
});

describe('the gold statements', () => {
  it('separates a statement that fails from one that returns nothing', async () => {
    const { gold, broken } = await checkGold(oracle, [
      ...CASES,
      { id: 'fails', category: 'ratio', probes: 'x', db: MINI_DB, question: 'q', sql: 'select * from nowhere' },
      { id: 'empty', category: 'ratio', probes: 'x', db: MINI_DB, question: 'q', sql: 'select * from items where id > 99' },
    ]);
    expect(gold.size).toBe(CASES.length);
    expect(broken.map((entry) => `${entry.id}:${entry.error}`)).toEqual([
      'fails:OperationalError: no such table: nowhere',
      'empty:gold returned no rows',
    ]);
  });

  it('catches a question that promises a width its gold does not return', async () => {
    const { broken } = await checkGold(oracle, [
      {
        id: 'wide',
        category: 'window',
        probes: 'x',
        db: MINI_DB,
        question: 'Show exactly two columns of items.',
        sql: 'select count(*) from items',
      },
    ]);
    expect(broken).toEqual([{ id: 'wide', error: 'question promises 2 columns, gold returns 1' }]);
  });
});

describe('the arms', () => {
  it('gives the inline arm the schema built from the synthesized definitions', async () => {
    const endpoint = await startEndpoint({ reply: (request) => reply(request.prompt, true) });
    try {
      const provider = createHttpProvider({ baseUrl: endpoint.url, apiKey: 'k', model: 'stub-model' });
      const prepared = await prepareAdversarial(settings(), { oracle, provider, cases: CASES });
      const inline = schemaForArm({ name: 'inline', notes: true, repairs: 0, linking: true, definitions: 'inline' }, MINI_DB, prepared);
      const plain = schemaForArm({ name: 'plain', notes: true, repairs: 0, linking: true }, MINI_DB, prepared);
      expect(inline).not.toBe(plain);
      expect(JSON.stringify(inline)).not.toBe(JSON.stringify(plain));
      // Every other arm reads the dataset's own descriptions.
      expect(schemaForArm({ name: 'meta', notes: true, repairs: 0, linking: true }, MINI_DB, prepared)).toBe(plain);
    } finally {
      await endpoint.close();
    }
  });

  it('falls back to the plain schema when the inline one was never built', () => {
    const prepared = { schemas: new Map([[MINI_DB, [{ table: 'items', columns: [] }]]]), inlineSchemas: new Map() };
    expect(schemaForArm({ name: 'inline', notes: true, repairs: 0, linking: true, definitions: 'inline' }, MINI_DB, prepared)).toEqual(
      prepared.schemas.get(MINI_DB),
    );
  });

  it('refuses a database it has no schema for', () => {
    expect(() => schemaForArm({ name: 'a', notes: true, repairs: 0, linking: true }, 'absent', { schemas: new Map(), inlineSchemas: new Map() })).toThrow(
      /no schema for absent/,
    );
  });

  it('names the arms it ran when a comparison asks for one that is not there', () => {
    expect(() => armNamed(new Map([['names', []]]), 'metadata')).toThrow(/the run has no 'metadata' arm; it ran names/);
  });

  it('pairs two arms case by case and reports the exact p value', () => {
    const outcomes = new Map([
      [
        'names',
        [
          { id: 'a', passed: true, strict: true, sql: '' },
          { id: 'b', passed: false, strict: false, sql: '' },
        ],
      ],
      [
        'metadata',
        [
          { id: 'a', passed: true, strict: true, sql: '' },
          { id: 'b', passed: true, strict: true, sql: '' },
        ],
      ],
    ]);
    const ablation = ablationFor(outcomes, 'names', 'metadata');
    expect(ablation).toMatchObject({ delta: 0.5, onlyFirst: 0, onlySecond: 1 });
    expect(ablation.p).toBeCloseTo(1, 10);
  });

  it('formats one line per arm', () => {
    const lines = armLines([
      {
        arm: 'names',
        passed: 1,
        total: 2,
        accuracy: 0.5,
        wilson: { low: 0.09, high: 0.9 },
        strictPassed: 1,
        executionErrors: 0,
        byCategory: { tie: { passed: 1, total: 1 } },
      },
    ]);
    expect(lines).toEqual(['names     1/2  50.0%  {"tie":{"passed":1,"total":1}}']);
  });
});

describe('a full run', () => {
  interface RunResult {
    readonly report: Record<string, unknown>;
    readonly printed: string[];
    readonly requests: number;
    readonly problems: readonly string[];
  }

  async function run(
    options: { readonly correct?: boolean; readonly cases?: readonly AdversarialCase[]; readonly dryRun?: boolean } = {},
  ): Promise<RunResult> {
    const endpoint = await startEndpoint({ reply: (request) => reply(request.prompt, options.correct ?? true) });
    try {
      const provider = createHttpProvider({ baseUrl: endpoint.url, apiKey: 'k', model: 'stub-model' });
      const result = await runAdversarial({ ...settings(), dryRun: options.dryRun ?? false }, { oracle, provider, cases: options.cases ?? CASES });
      return {
        report: result.report,
        printed: [...result.lines, ...result.problems],
        requests: endpoint.requests.length,
        problems: result.problems,
      };
    } finally {
      await endpoint.close();
    }
  }

  it('scores every arm, pairs names against metadata, and buckets the categories', async () => {
    const result = await run();
    const arms = result.report.arms as { arm: string; accuracy: number }[];
    expect(arms.map((arm) => arm.arm)).toEqual([
      'names',
      'definitions',
      'inline-definitions',
      'metadata',
      'synthetic',
      'adaptive',
    ]);
    for (const arm of arms) expect(arm.accuracy).toBe(1);
    const ablations = result.report.ablations as Record<string, { delta: number; onlyFirst: number; onlySecond: number }>;
    // The headline pairing is names against metadata — the arms it names, not the arm next
    // to it in the table.
    expect(Object.keys(ablations)).toEqual(['names -> metadata', 'metadata -> synthetic', 'metadata -> adaptive']);
    expect(ablations['names -> metadata']).toMatchObject({ delta: 0, onlyFirst: 0, onlySecond: 0 });
    const perCategory = result.report.perCategory as Record<string, { cases: number; names: number; metadata: number }>;
    expect(perCategory.tie).toMatchObject({ cases: 1, names: 1, metadata: 1 });
    expect(perCategory.window).toMatchObject({ cases: 1, names: 1, metadata: 1 });
    expect(result.report.cases).toBe(CASES.length);
    expect(result.report.gold).toEqual({ runnable: CASES.length, broken: [] });
  });

  it('scores a wrong answer as wrong and lists it with the question it came from', async () => {
    const result = await run({ correct: false });
    for (const arm of result.report.arms as { accuracy: number }[]) expect(arm.accuracy).toBe(0);
    const failures = result.report.failures as Record<string, { id: string; question?: string }[]>;
    expect(failures.names?.length).toBe(CASES.length);
    expect(failures.names?.[0]?.question).toBeDefined();
  });

  it('refuses to score a case set whose gold does not run, and says which case', async () => {
    const result = await run({
      cases: [...CASES, { id: 'broken', category: 'ratio', probes: 'x', db: MINI_DB, question: 'q', sql: 'select * from nowhere' }],
    });
    expect(result.report.arms).toEqual([]);
    expect(result.report.ablations).toEqual({});
    const gold = result.report.gold as { broken: { id: string; error: string }[] };
    expect(gold.broken.map((entry) => entry.id)).toEqual(['broken']);
    // No arm ran, so nothing was spent on the model.
    expect(result.requests).toBe(0);
  });
});

describe('a peer that fails without naming the failure', () => {
  it('records the case as broken with a reason a reader can act on', async () => {
    // `{"ok": false}` with no `error` is a protocol violation, and a peer that violates the
    // protocol must not make the harness print `undefined` where a reason belongs.
    const script = join(root, 'mute_oracle.py');
    writeFileSync(
      script,
      ['import json, sys', 'for line in sys.stdin:', '    rid = json.loads(line)["id"]', '    print(json.dumps({"id": rid, "ok": False}), flush=True)', ''].join('\n'),
    );
    const mute = createOracle(script, join(data, 'dev_databases'));
    try {
      const { broken } = await checkGold(mute, CASES);
      expect(broken.map((entry) => entry.error)).toEqual(['failed', 'failed']);
    } finally {
      await mute.close();
    }
  });
});

describe('an engine that dies under one statement', () => {
  it('scores the case as wrong and keeps the run, instead of crashing it', async () => {
    const hostile = {
      run: async (db: string, sql: string) => {
        if (sql.trim() === 'select 1') throw new Error('oracle process died');
        return oracle.run(db, sql);
      },
      databaseRoot: oracle.databaseRoot,
      close: () => oracle.close(),
    };
    const endpoint = await startEndpoint({ reply: (request) => reply(request.prompt, false) });
    try {
      const provider = createHttpProvider({ baseUrl: endpoint.url, apiKey: 'k', model: 'stub-model' });
      const outcome = await runAdversarial(settings(), { oracle: hostile, provider, cases: CASES });
      const failures = outcome.report.failures as Record<string, { error?: string }[]>;
      expect(failures.names?.every((entry) => entry.error === 'oracle process died')).toBe(true);
      for (const arm of outcome.report.arms as { accuracy: number }[]) expect(arm.accuracy).toBe(0);
      // Every arm at zero is the harness seeing no signal, and it says so.
      expect(outcome.problems).toEqual(['GATE FAILED: no arm scored above 5%; the harness sees no signal']);
    } finally {
      await endpoint.close();
    }
  });
});

describe('a report built without every arm', () => {
  it('leaves out the pairings it cannot make', () => {
    const prepared = {
      settings: settings(),
      cases: CASES,
      dbs: [MINI_DB],
      schemas: new Map(),
      inlineSchemas: new Map(),
      definitions: new Map(),
      synthesized: new Map(),
      gold: new Map(),
      broken: [],
    };
    const outcomes = new Map([
      ['names', [{ id: 'tie-1', passed: true, strict: true, sql: '' }]],
      ['metadata', [{ id: 'tie-1', passed: true, strict: true, sql: '' }]],
    ]);
    const report = adversarialReport(prepared, [], outcomes);
    // Only the pairing whose two arms both ran is present; the other two are absent rather
    // than present with a delta against nothing.
    expect(Object.keys(report.ablations as Record<string, unknown>)).toEqual(['names -> metadata']);
  });
});

describe('a dry run', () => {
  it('runs every gold statement, calls no model, and reports what it checked', async () => {
    const endpoint = await startEndpoint({ reply: (request) => reply(request.prompt, true) });
    try {
      const provider = createHttpProvider({ baseUrl: endpoint.url, apiKey: 'k', model: 'stub-model' });
      const outcome = await runAdversarial({ ...settings(), dryRun: true }, { oracle, provider, cases: CASES });
      expect(outcome.report).toMatchObject({ cases: CASES.length, gold: CASES.length, broken: [] });
      expect(outcome.lines).toEqual([
        `dry run: ${String(CASES.length)}/${String(CASES.length)} gold statements run, all widths agree with the questions`,
      ]);
      expect(outcome.problems).toEqual([]);
      // Nothing was asked: a dry run that spends a call is not a dry run.
      expect(endpoint.requests).toHaveLength(0);
    } finally {
      await endpoint.close();
    }
  });
});

describe('the artifact', () => {
  it('writes a dry report beside the measured one instead of over it', () => {
    const measured = join(root, 'artifacts', 'adversarial.json');
    const dry = writeAdversarialArtifact({ ...settings(), dryRun: true, out: measured }, { cases: 1 });
    expect(dry).toBe(join(root, 'artifacts', 'adversarial-dry.json'));
    expect(JSON.parse(readFileSync(dry, 'utf8'))).toEqual({ cases: 1 });
    // The measured artifact is untouched by a dry run.
    expect(() => readFileSync(measured, 'utf8')).toThrow(/ENOENT/);
  });

  it('writes the measured report to the path it was given', () => {
    const path = writeAdversarialArtifact({ ...settings(), dryRun: false, out: join(root, 'measured.json') }, { cases: 2 });
    expect(JSON.parse(readFileSync(path, 'utf8'))).toEqual({ cases: 2 });
  });
});

describe('the command line', () => {
  it('refuses a dataset that does not describe the databases its cases use', async () => {
    // The hand-written cases name BIRD's six databases; a dataset with one database cannot
    // describe them, and the run has to say so instead of scoring every case as a model
    // failure. That is the only path this machine can reach: the real split is 2 GB of
    // databases the CI job downloads and this test does not.
    await expect(
      main(
        { BIRD_DATA: data, BIRD_PROFILE_CACHE: join(root, 'profiles'), ADVERSARIAL_OUT: join(root, 'cli.json'), LLM_API_KEY: 'k' },
        ['--dry-run'],
        root,
      ),
    ).rejects.toThrow(/dev_tables\.json has no entry for/);
  });
});
