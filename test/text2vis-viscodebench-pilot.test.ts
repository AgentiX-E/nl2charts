const FIXTURE = JSON.parse(
  readFileSync(new URL('../eval/text2vis/viscodebench-pilot-fixture.json', import.meta.url), 'utf-8'),
) as { samples: Record<string, { id: string; ok: boolean; series: SeriesLogRecord[] }> };
const ORACLE = JSON.parse(
  readFileSync(new URL('../eval/text2vis/viscodebench-pilot-oracle.json', import.meta.url), 'utf-8'),
) as PilotOracle;

const logOf = (key: string): SeriesLogRecord[] => FIXTURE.samples[key]!.series;

/** Build figure data directly from a fixture, bypassing emit (emit is tested separately). */
const figOf = (key: string): FigData => parseSeriesLog(logOf(key));

describe('emitVisualisationCode', () => {
  it('wraps a line spec in the exact upstream marker region', () => {
    const code = emitVisualisationCode({ kind: 'line', x: [0, 1, 2], y: [0, 1, 4] });
    expect(code).toContain('##START VISUALISATION CODE');
    expect(code).toContain('##END VISUALISATION CODE');
    expect(code).toContain('plt.plot(');
    expect(code.indexOf('##START VISUALISATION CODE')).toBeLessThan(code.indexOf('plt.plot('));
    expect(code.indexOf('plt.plot(')).toBeLessThan(code.indexOf('##END VISUALISATION CODE'));
  });

  it('emits the four supported chart kinds with their matplotlib call', () => {
    expect(emitVisualisationCode({ kind: 'line', x: [0, 1], y: [1, 2] })).toContain('plt.plot(');
    expect(emitVisualisationCode({ kind: 'scatter', x: [0, 1], y: [1, 2] })).toContain('plt.scatter(');
    expect(emitVisualisationCode({ kind: 'bar', x: [0, 1], y: [1, 2] })).toContain('plt.bar(');
    expect(emitVisualisationCode({ kind: 'pie', x: [10, 20] })).toContain('plt.pie(');
  });

  it('CHART_KINDS lists exactly the four kinds the worker can execute', () => {
    expect([...CHART_KINDS].sort()).toEqual(['bar', 'line', 'pie', 'scatter']);
  });

  it('refuses a spec whose kind is outside the supported set', () => {
    expect(() => emitVisualisationCode({ kind: 'heatmap' as ChartKind, x: [0], y: [1] })).toThrow(/kind/i);
  });

  it('refuses a line/scatter/bar spec without a matching y length', () => {
    expect(() => emitVisualisationCode({ kind: 'line', x: [0, 1, 2], y: [0, 1] })).toThrow(/length/i);
  });

  it('refuses empty data and non-finite coordinates', () => {
    expect(() => emitVisualisationCode({ kind: 'line', x: [], y: [] })).toThrow(/empty/i);
    expect(() => emitVisualisationCode({ kind: 'line', x: [0, NaN], y: [1, 2] })).toThrow(/finite/i);
  });

  it('quotes a label safely so a spec cannot break out of the emitted string literal', () => {
    const code = emitVisualisationCode({ kind: 'line', x: [0], y: [1], label: "a'\\b" });
    expect(code).toContain("label=\"a'\\\\b\"");
  });

  it('omits the label argument when the spec has no label', () => {
    expect(emitVisualisationCode({ kind: 'line', x: [0], y: [1] })).not.toContain('label=');
  });
});

describe('parseSeriesLog', () => {
  it('groups a real line log into one axis with one series and finite coordinates', () => {
    const fig = figOf('line-base');
    expect(Object.keys(fig)).toEqual(['ax_0']);
    expect(fig.ax_0).toHaveLength(1);
    expect(fig.ax_0![0]!.pltFunc).toBe('plot');
    expect(fig.ax_0![0]!.data.x).toHaveLength(4);
  });

  it('min-max normalises each coordinate axis to [0, 1]', () => {
    const s = figOf('line-base').ax_0![0]!;
    expect(s.data.x![0]).toBeCloseTo(0, 10);
    expect(s.data.x![s.data.x!.length - 1]!).toBeCloseTo(1, 10);
    expect(s.data.y![0]).toBeCloseTo(0, 10);
    expect(s.data.y![s.data.y!.length - 1]!).toBeCloseTo(1, 10);
  });

  it('normalises a shape-identical translate to the same coordinates — the metric is translation-invariant', () => {
    const base = figOf('line-base').ax_0![0]!.data.y!;
    const translated = figOf('line-translate').ax_0![0]!.data.y!;
    expect(translated).toEqual(base);
  });

  it('normalises a pie series by proportion, not min-max', () => {
    const s = figOf('pie-base').ax_0![0]!;
    expect(s.pltFunc).toBe('pie');
    const sum = s.data.x!.reduce((a, b) => a + b, 0);
    expect(sum).toBeCloseTo(1, 10);
  });

  it('keeps scatter marker size as z and normalises it on the shared axis', () => {
    const s = figOf('scatter-base').ax_0![0]!;
    expect(s.pltFunc).toBe('scatter');
    expect(s.data.z).toBeDefined();
  });

  it('merges multiple same-type series within one axis (upstream group_fig_data_by_plt_func)', () => {
    const two: SeriesLogRecord[] = [
      { axis_id: 'ax_0', plot_func_id: 'pf_1', plt_func: 'scatter', data_series: [{ x: [0, 1], y: [2, 4], s: [5, 5] }] },
      { axis_id: 'ax_0', plot_func_id: 'pf_2', plt_func: 'scatter', data_series: [{ x: [3, 4], y: [6, 8], s: [5, 5] }] },
    ];
    const fig = parseSeriesLog(two);
    expect(fig.ax_0).toHaveLength(1); // merged into one scatter cloud
    expect(fig.ax_0![0]!.data.x).toHaveLength(4);
  });

  it('keeps plot series separate (upstream preserves curve identity for lines)', () => {
    // A plot series needs an explicit linestyle; upstream reclassifies a linestyle-less plot as
    // scatter (default "None"), so a genuine line must carry linestyle:'-'.
    const two: SeriesLogRecord[] = [
      { axis_id: 'ax_0', plot_func_id: 'pf_1', plt_func: 'plot', data_series: [{ x: [0, 1], y: [2, 4], linestyle: '-' }] },
      { axis_id: 'ax_0', plot_func_id: 'pf_2', plt_func: 'plot', data_series: [{ x: [0, 1], y: [5, 7], linestyle: '-' }] },
    ];
    const fig = parseSeriesLog(two);
    expect(fig.ax_0).toHaveLength(2);
    expect(fig.ax_0!.every((s) => s.pltFunc === 'plot')).toBe(true);
  });

  it('reclassifies a linestyle-less plot as scatter with z=5, as upstream does', () => {
    const rec: SeriesLogRecord[] = [
      { axis_id: 'ax_0', plot_func_id: 'pf_1', plt_func: 'plot', data_series: [{ x: [0, 1], y: [2, 4], linestyle: 'None' }] },
    ];
    const fig = parseSeriesLog(rec);
    expect(fig.ax_0![0]!.pltFunc).toBe('scatter');
    expect(fig.ax_0![0]!.data.z).toHaveLength(2);
    // z is min-max normalized like every axis; a constant z=5 range is widened by eps, so upstream
    // scales both values to 0. We pin that exact behaviour rather than the pre-normalization 5.
    expect(fig.ax_0![0]!.data.z!.every((v) => v === 0)).toBe(true);
  });

  it('drops non-plottable series (axvline/axhline) and empty logs', () => {
    const rec: SeriesLogRecord[] = [
      { axis_id: 'ax_0', plot_func_id: 'pf_1', plt_func: 'axvline', data_series: [{ x: [1] }] },
      { axis_id: 'ax_0', plot_func_id: 'pf_2', plt_func: 'plot', data_series: [] },
    ];
    // Upstream uses a defaultdict: an axis with no ingested series has no key at all.
    expect(Object.keys(parseSeriesLog(rec))).toHaveLength(0);
  });

  it('handles a degenerate (constant) axis without dividing by zero', () => {
    const s = figOf('line-flat').ax_0![0]!;
    expect(s.data.y!.every((v) => Number.isFinite(v))).toBe(true);
  });
});

describe('compareSeries / compareAxes / compareFigures', () => {
  it('compareSeries routes plot→plot through continuous F1', () => {
    const b = figOf('line-base').ax_0![0]!;
    const w = figOf('line-parabola-tweak').ax_0![0]!;
    const s = compareSeries(w, b);
    expect(s).toBeGreaterThan(0);
    expect(s).toBeLessThanOrEqual(1);
  });

  it('compareSeries routes pie→pie through the discrete comparator', () => {
    const b = figOf('pie-base').ax_0![0]!;
    const d = figOf('pie-different').ax_0![0]!;
    expect(compareSeries(d, b)).toBeCloseTo(2 / 3, 6);
  });

  it('compareSeries falls back to scatter for mismatched function types', () => {
    const line = figOf('line-base').ax_0![0]!;
    const scatter = figOf('scatter-base').ax_0![0]!;
    expect(Number.isFinite(compareSeries(scatter, line))).toBe(true);
  });

  it('compareAxes solves the series-assignment and returns a score in [0,1]', () => {
    const s = compareAxes(figOf('line-parabola-tweak').ax_0!, figOf('line-base').ax_0!);
    expect(s).toBeGreaterThan(0.8);
    expect(s).toBeLessThanOrEqual(1);
  });

  it('compareFigures matches figures by optimal axis assignment', () => {
    const s = compareFigures(figOf('line-base'), figOf('line-base'));
    expect(s).toBeCloseTo(1, 10);
  });

  it('compareFigures handles figures with a different number of axes', () => {
    const twoAxes: FigData = { ...figOf('line-base'), ax_1: figOf('scatter-base').ax_0! };
    const s = compareFigures(twoAxes, figOf('line-base'));
    expect(s).toBeGreaterThanOrEqual(0);
    expect(s).toBeLessThanOrEqual(1);
  });
});

describe('displayedDataSimilarity — authority oracle', () => {
  it('reproduces every upstream authority pair within 1e-6', () => {
    for (const [pair, expected] of Object.entries(ORACLE.pairs)) {
      const [pred, gt] = pair.split('|') as [string, string];
      const actual = displayedDataSimilarity(logOf(pred), logOf(gt));
      expect(actual, pair).toBeCloseTo(expected, 6);
    }
  });

  it('scores a shape-identical translate at 1.0 — asserted, not mistaken for a bug', () => {
    expect(displayedDataSimilarity(logOf('line-translate'), logOf('line-base'))).toBeCloseTo(1, 8);
    expect(displayedDataSimilarity(logOf('pie-proportional'), logOf('pie-base'))).toBeCloseTo(1, 8);
  });

  it('separates a genuinely different pie from its base', () => {
    expect(displayedDataSimilarity(logOf('pie-different'), logOf('pie-base'))).toBeCloseTo(2 / 3, 6);
  });

  it('refuses empty prediction or ground-truth logs rather than scoring 0/0 as perfect', () => {
    expect(() => displayedDataSimilarity([], logOf('line-base'))).toThrow(/empty/i);
    expect(() => displayedDataSimilarity(logOf('line-base'), [])).toThrow(/empty/i);
  });
});

describe('pilotSelfCheck / runPilot / entryPilot', () => {
  it('reports instrumented status and zero LLM calls — never a leaderboard reading', () => {
    const report = pilotSelfCheck(ORACLE, logOf);
    expect(report.status).toBe('instrumented');
    expect(report.llmCalls).toBe(0);
    expect(report.groundTruthRequired).toBe(false);
  });

  it('every oracle pair passes inside the self-check', () => {
    const report = pilotSelfCheck(ORACLE, logOf);
    expect(report.checks).toHaveLength(Object.keys(ORACLE.pairs).length);
    expect(report.checks.every((c) => c.pass)).toBe(true);
  });

  it('flags drift when an oracle value is wrong', () => {
    const drifted: PilotOracle = { ...ORACLE, pairs: { ...ORACLE.pairs, 'pie-base|pie-base': 0.5 } };
    const report = pilotSelfCheck(drifted, logOf);
    expect(report.checks.some((c) => !c.pass)).toBe(true);
  });

  it('runPilot prints a human report and returns 0 when all pass, 1 on drift', () => {
    const lines: string[] = [];
    expect(runPilot(ORACLE, logOf, (l) => lines.push(l))).toBe(0);
    expect(lines.join('\n')).toMatch(/instrumented/);
    const drifted: PilotOracle = { ...ORACLE, pairs: { ...ORACLE.pairs, 'line-base|line-base': 0 } };
    expect(runPilot(drifted, logOf, () => {})).toBe(1);
  });

  it('entryPilot returns undefined when only imported', () => {
    expect(entryPilot(undefined, 'file:///elsewhere.ts', () => {}, () => ORACLE, logOf)).toBeUndefined();
  });

  it('entryPilot reads the oracle via the injected reader and runs when it is the entry', () => {
    const url = 'file:///pilot.ts';
    const lines: string[] = [];
    const code = entryPilot('/pilot.ts', url, (l) => lines.push(l), () => ORACLE, logOf, url);
    expect(code).toBe(0);
    expect(lines.join('\n')).toMatch(/instrumented/);
  });

  it('entryPilot surfaces a read failure as exit code 1 with a message', () => {
    const url = 'file:///pilot.ts';
    const lines: string[] = [];
    const code = entryPilot('/pilot.ts', url, (l) => lines.push(l), () => { throw new Error('no oracle'); }, logOf, url);
    expect(code).toBe(1);
    expect(lines.join('\n')).toMatch(/no oracle/);
  });
});

