/**
 * TDD for the VisCodeBench end-to-end pilot: emit → log → parse → score.
 *
 * r212 delivered the comparator (`viscodebench-score.ts`) but its input contract — the figure data
 * `read_t2v_log_dir` produces — had no producer in this repository, so the "generate → log → score"
 * loop had never been closed locally. This suite pins the missing half:
 *
 *   1. `emitVisualisationCode` — a structured chart spec becomes Python with the upstream marker
 *      region, which the real log worker (`viscodebench_log_worker.py`) executes.
 *   2. `parseSeriesLog` — upstream `series.jsonl` records become normalized, grouped figure data
 *      (min-max per axis, pie by proportion; shape-identical translates therefore score 1.0).
 *   3. `compareSeries` / `compareAxes` / `compareFigures` — the nested assignment that wraps the
 *      r212 comparators into a single Displayed Data Similarity.
 *   4. `displayedDataSimilarity` + `pilotSelfCheck` — the whole loop scored against an authority
 *      oracle generated by upstream `calculate_similarity_score` (scipy 1.17 / numpy 2.3.5).
 *
 * Fixtures are real logs emitted by the local worker over the recorded matplotlib version. No model
 * is called, no network is touched, and no leaderboard number is claimed: the report status stays
 * `instrumented`. The point is to prove the harness is wired correctly at ¥0, so a future Crew or
 * refinement dispatch scores through a path that is already pinned to authority.
 */
