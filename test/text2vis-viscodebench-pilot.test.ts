describe('numeric edge branches', () => {
  it('minMax scales a live range and leaves a degenerate range unchanged', () => {
    expect(minMax([0, 5, 10], 0, 10)).toEqual([0, 0.5, 1]);
    // lo === hi -> falls through to an unchanged copy (upstream widens before calling, but the
    // guard is exercised directly here so the defensive branch is pinned).
    expect(minMax([7, 7], 7, 7)).toEqual([7, 7]);
    // Non-finite bounds likewise leave the array unchanged.
    expect(minMax([1, 2], Infinity, Infinity)).toEqual([1, 2]);
  });

  it('simToCost maps NaN to 1 and clamps out-of-range similarities', () => {
    expect(simToCost(NaN)).toBe(1);
    expect(simToCost(0.25)).toBeCloseTo(0.75, 10);
    expect(simToCost(-0.5)).toBe(1); // clamped to 0 similarity -> cost 1
    expect(simToCost(1.8)).toBe(0); // clamped to 1 similarity -> cost 0
  });

  it('parse: an all-NaN x series is dropped (filteredX.length===0 branch)', () => {
    const rec: SeriesLogRecord[] = [
      { axis_id: 'ax_0', plot_func_id: 'pf_1', plt_func: 'plot', data_series: [{ x: [NaN, Infinity], y: [1, 2], linestyle: '-' }] },
    ];
    expect(Object.keys(parseSeriesLog(rec))).toHaveLength(0);
  });

  it('parse: a plot series with no y is dropped (n===0 branch)', () => {
    const rec: SeriesLogRecord[] = [
      { axis_id: 'ax_0', plot_func_id: 'pf_1', plt_func: 'plot', data_series: [{ x: [0, 1], linestyle: '-' }] },
    ];
    expect(Object.keys(parseSeriesLog(rec))).toHaveLength(0);
  });

  it('parse: a scatter series without y uses x as y (the ?? filteredX fallback)', () => {
    const rec: SeriesLogRecord[] = [
      { axis_id: 'ax_0', plot_func_id: 'pf_1', plt_func: 'scatter', data_series: [{ x: [0, 1, 2], z: [5, 5, 5] }] },
    ];
    const s = parseSeriesLog(rec).ax_0![0]!;
    expect(s.data.y).toEqual(s.data.x);
  });

  it('compareSeries: scatter points with no y array fall back to 0 for y', () => {
    const noY: FigSeries = { pltFunc: 'scatter', data: { x: [0, 1] }, name: '', plotFuncId: 'p' };
    const withY: FigSeries = { pltFunc: 'scatter', data: { x: [0, 1], y: [1, 2] }, name: '', plotFuncId: 'g' };
    expect(Number.isFinite(compareSeries(noY, withY))).toBe(true);
  });

  it('compareSeries: a fully y-less scatter pair is still finite (?? 0 for every point)', () => {
    const a: FigSeries = { pltFunc: 'scatter', data: { x: [0, 1] }, name: '', plotFuncId: 'p' };
    const b: FigSeries = { pltFunc: 'scatter', data: { x: [2, 3] }, name: '', plotFuncId: 'g' };
    expect(Number.isFinite(compareSeries(a, b))).toBe(true);
  });

  it('compareAxes and compareFigures route a NaN similarity through simToCost', () => {
    // A plot vs a single-point comparator can produce NaN; simToCost turns it into cost 1.
    const a: FigSeries = { pltFunc: 'plot', data: { x: [0], y: [0] }, name: '', plotFuncId: 'p' };
    const b: FigSeries = { pltFunc: 'plot', data: { x: [0], y: [0] }, name: '', plotFuncId: 'g' };
    expect(Number.isFinite(compareAxes([a], [b]))).toBe(true);
    expect(Number.isFinite(compareFigures({ ax_0: [a] }, { ax_0: [b] }))).toBe(true);
  });
});

