/**
 * A faithful TypeScript port of the VisCodeBench score engine (`t2v_eval`), reduced to the
 * LLM-independent part that can be verified without the private references.
 *
 * Why this exists. The VisCodeBench row stayed `absent` for twelve rounds under a plan item that
 * said "pilot, ¥3-6, absent -> measured". The reason was never a fetch problem: the sample inputs
 * are public and the scorer is open source. The reason is that the primary metric — Displayed Data
 * Similarity — is computed on the leaderboard server against **private** reference logs, so a score
 * over the full split cannot exist in this repository. Calling the row `measured` would have meant
 * publishing a number this repository does not hold. The honest state is `instrumented`: the metric
 * and its harness exist, no dispatch has produced a number, and the difference from "never built"
 * is now visible in the coverage table.
 *
 * What is ported. Every comparator in `t2v_eval/evaluation/ddata_similarity.py`:
 * `get_score` (Hungarian / Jonker-Volgenant assignment via scipy), `compare_scatter` (Mahalanobis),
 * `compare_discrete` (1-D Mahalanobis), `compare_continuous` (arc-length interpolation F1),
 * `compare_axes` / `compare_figures` (nested assignment), and chart-type accuracy (set inclusion).
 * The accessibility metric is deliberately NOT ported: upstream needs pytesseract OCR + KMeans over
 * rendered pixels, neither of which exists here, and pretending otherwise would be a fake reading.
 *
 * Correctness is pinned to authority, not to a guess. `eval/text2vis/viscodebench-oracle.json`
 * holds values generated by scipy 1.17 / numpy 2.3.5 from the upstream formulas. `scoreEngineSelfCheck`
 * re-derives each one; a drift in the port fails a test instead of silently changing a future score.
 *
 * This module has no I/O and calls no model. It is imported by tests and by the `bench:text2vis:
 * viscodebench-score` command, which prints the self-check as a machine-readable report.
 */

/** A plotted point. Upstream stores series as parallel `x` / `y` arrays. */
export type Point = readonly [number, number];

/** Parallel coordinate arrays, the shape `read_t2v_log_dir` produces per series. */
export interface Series {
  readonly x: readonly number[];
  readonly y: readonly number[];
}

/** Expected values produced by the upstream algorithm; see viscodebench-oracle.json. */
export interface ScoreOracle {
  readonly getScore: {
    readonly identity: number;
    readonly perfect: number;
    readonly rect2x3: number;
    readonly rect3x2: number;
    readonly allMax: number;
    readonly mixed: number;
    readonly oneZero: number;
  };
  readonly scatter: { readonly identical: number; readonly shifted: number; readonly noisy: number; readonly noisyCostMatrix: readonly (readonly number[])[] };
  readonly discrete: { readonly identical: number; readonly shifted: number };
  readonly cov2: { readonly matrix: readonly (readonly number[])[]; readonly inverse: readonly (readonly number[])[] };
  readonly continuous: Readonly<Record<string, { readonly f1: number; readonly recall: number; readonly precision: number }>>;
}

import { readFileSync } from 'node:fs';
import { isEntry } from '../entry.js';

const EPS = 1e-5;
const clamp01 = (n: number): number => Math.max(0, Math.min(1, n));

/**
 * Pad a cost matrix to square with cost 1.0 — exactly upstream's `_pad_to_square`.
 * An empty or ragged matrix is a caller error and is refused rather than scored.
 */
export function padToSquare(mat: readonly (readonly number[])[]): number[][] {
  if (mat.length === 0) throw new Error('padToSquare: empty matrix has no assignment');
  const width = mat[0]!.length;
  if (mat.some((row) => row.length !== width)) {
    throw new Error('padToSquare: ragged matrix');
  }
  if (width === 0) throw new Error('padToSquare: empty matrix has no assignment');
  const h = mat.length;
  const w = width;
  if (h === w) return mat.map((row) => [...row]);
  const n = Math.max(h, w);
  const padded = Array.from({ length: n }, () => Array<number>(n).fill(1.0));
  for (let i = 0; i < h; i++) for (let j = 0; j < w; j++) padded[i]![j] = mat[i]![j]!;
  return padded;
}

/** The result of a minimum-cost perfect matching. */
export interface Assignment {
  readonly rows: number[];
  readonly cols: number[];
  readonly cost: number;
}

/**
 * Solve the linear assignment problem with the Hungarian (Kuhn-Munkres) algorithm in O(n^3).
 * Works on a rectangular n<=m matrix; `getScore` pads to square before calling, matching upstream.
 * Ties may resolve to a different column than scipy's JV variant, but the minimum total cost is
 * identical, which is all the score uses.
 */
export function linearSumAssignment(mat: readonly (readonly number[])[]): Assignment {
  const n = mat.length;
  if (n === 0) return { rows: [], cols: [], cost: 0 };
  const m = mat[0]!.length;
  // Potentials u (rows) and v (cols), matching p (column -> row) and the augmenting-path way.
  const u = Array<number>(n + 1).fill(0);
  const v = Array<number>(m + 1).fill(0);
  const p = Array<number>(m + 1).fill(0);
  const way = Array<number>(m + 1).fill(0);

  for (let i = 1; i <= n; i++) {
    p[0] = i;
    let j0 = 0;
    const minv = Array<number>(m + 1).fill(Infinity);
    const used = Array<boolean>(m + 1).fill(false);
    do {
      used[j0] = true;
      const i0 = p[j0]!;
      let delta = Infinity;
      let j1 = 0;
      for (let j = 1; j <= m; j++) {
        if (used[j]) continue;
        const cur = mat[i0 - 1]![j - 1]! - u[i0]! - v[j]!;
        if (cur < minv[j]!) {
          minv[j]! = cur;
          way[j]! = j0;
        }
        if (minv[j]! < delta) {
          delta = minv[j]!;
          j1 = j;
        }
      }
      for (let j = 0; j <= m; j++) {
        if (used[j]) {
          u[p[j]!]! += delta;
          v[j]! -= delta;
        } else {
          minv[j]! -= delta;
        }
      }
      j0 = j1;
    } while (p[j0] !== 0);
    do {
      const j1 = way[j0]!;
      p[j0]! = p[j1]!;
      j0 = j1;
    } while (j0 !== 0);
  }

  const colOfRow = new Map<number, number>();
  let cost = 0;
  for (let j = 1; j <= m; j++) {
    if (p[j] === 0) continue;
    colOfRow.set(p[j]! - 1, j - 1);
    cost += mat[p[j]! - 1]![j - 1]!;
  }
  const rows = [...colOfRow.keys()].sort((a, b) => a - b);
  const cols = rows.map((r) => colOfRow.get(r) ?? -1);
  return { rows, cols, cost };
}

/**
 * Upstream `get_score`: pad, assign, score = 1 - min(1, average matched cost).
 */
export function getScore(costMat: readonly (readonly number[])[]): number {
  const cost = padToSquare(costMat);
  const k = cost.length;
  const a = linearSumAssignment(cost);
  const avg = a.cost / k;
  return 1 - Math.min(1, avg);
}

/** Euclidean distance between two points. */
export function euclidean(a: Point, b: Point): number {
  let sum = 0;
  for (let i = 0; i < a.length; i++) sum += (a[i]! - b[i]!) ** 2;
  return Math.sqrt(sum);
}

/** Sample covariance of a set of 2-D points, with the eps ridge upstream adds. */
export function cov2(points: readonly Point[]): number[][] {
  const n = points.length;
  const mx = points.reduce((s, p) => s + p[0], 0) / n;
  const my = points.reduce((s, p) => s + p[1], 0) / n;
  let xx = 0, xy = 0, yy = 0;
  for (const p of points) {
    xx += (p[0] - mx) ** 2;
    xy += (p[0] - mx) * (p[1] - my);
    yy += (p[1] - my) ** 2;
  }
  const d = n - 1;
  return [
    [xx / d + EPS, xy / d],
    [xy / d, yy / d + EPS],
  ];
}

/** Inverse of a 2x2 matrix (determinant assumed nonzero after the ridge). */
export function inverse2(m: readonly (readonly number[])[]): number[][] {
  const a = m[0]![0]!, b = m[0]![1]!;
  const c = m[1]![0]!, d = m[1]![1]!;
  const det = a * d - b * c;
  return [
    [d / det, -b / det],
    [-c / det, a / det],
  ];
}

/**
 * Mahalanobis cost matrix between predicted and ground-truth point clouds.
 * Upstream: V = cov(gt.T) + eps*I; VI = inv(V).T; cdist(..., 'mahalanobis', VI=VI); clip to 1.
 * For a single GT point it falls back to euclidean. NaNs become max cost.
 */
export function mahalanobisCost(
  pred: readonly Point[],
  gt: readonly Point[],
): number[][] {
  let vi: number[][];
  let fallback = false;
  if (gt.length === 1) {
    fallback = true;
    vi = [[1, 0], [0, 1]]; // unused on the fallback path
  } else {
    const inv = inverse2(cov2(gt));
    // Upstream uses inv(V).T; for symmetric V this equals inv(V).
    vi = [[inv[0]![0]!, inv[1]![0]!], [inv[0]![1]!, inv[1]![1]!]];
  }
  const mat: number[][] = [];
  for (const p of pred) {
    const row: number[] = [];
    for (const g of gt) {
      const dx = p[0]! - g[0]!;
      const dy = p[1]! - g[1]!;
      let dist: number;
      if (fallback) {
        dist = Math.hypot(dx, dy);
      } else {
        // sqrt( d^T VI d )
        const q = vi[0]![0]! * dx * dx + (vi[0]![1]! + vi[1]![0]!) * dx * dy + vi[1]![1]! * dy * dy;
        dist = Math.sqrt(Math.max(0, q));
      }
      row.push(Number.isNaN(dist) ? 1.0 : Math.min(1.0, dist));
    }
    mat.push(row);
  }
  return mat;
}

/** Upstream `compare_scatter` for a multi-dimensional scatter cloud. */
export function compareScatter(pred: readonly Point[], gt: readonly Point[]): number {
  return getScore(mahalanobisCost(pred, gt));
}

/** 1-D Mahalanobis cost (pie slices); single GT value falls back to euclidean. */
function discreteCost(pred: readonly number[], gt: readonly number[]): number[][] {
  if (gt.length === 1) {
    return pred.map((pt) => [Math.min(1, Math.abs(pt - gt[0]!))]);
  }
  const mean = gt.reduce((s, v) => s + v, 0) / gt.length;
  let variance = 0;
  for (const v of gt) variance += (v - mean) ** 2;
  variance /= gt.length - 1;
  const vi = 1.0 / variance;
  return pred.map((pt) => gt.map((gtVal) => Math.min(1, Math.sqrt(Math.max(0, (pt - gtVal) ** 2 * vi)))));
}

/** Upstream `compare_discrete` for pie charts. */
export function compareDiscrete(pred: readonly number[], gt: readonly number[]): number {
  return getScore(discreteCost(pred, gt));
}

/**
 * Upstream `get_cont_recall_new`: parametric (arc-length) interpolation recall, vectorised in
 * numpy and reproduced here with the same trapezoidal interval weights.
 */
export function arcLengthRecall(
  px: readonly number[],
  py: readonly number[],
  gx: readonly number[],
  gy: readonly number[],
  eps: number,
): number {
  const parametrise = (xs: readonly number[], ys: readonly number[]): number[] => {
    const t = [0];
    let acc = 0;
    for (let i = 1; i < xs.length; i++) {
      acc += Math.hypot(xs[i]! - xs[i - 1]!, ys[i]! - ys[i - 1]!);
      t.push(acc);
    }
    if (t[t.length - 1]! === 0) t[t.length - 1] = eps;
    const last = t[t.length - 1]!;
    return t.map((v) => v / last);
  };
  const pt = parametrise(px, py);
  const gt = parametrise(gx, gy);
  const n = gt.length;
  if (n < 2) return 0;

  const interval: number[] = new Array(n);
  interval[0] = (gt[1]! - gt[0]!) / 2;
  interval[n - 1] = (gt[n - 1]! - gt[n - 2]!) / 2;
  for (let i = 1; i < n - 1; i++) interval[i] = (gt[i + 1]! - gt[i - 1]!) / 2;

  const interp = (query: number, xs: readonly number[], ys: readonly number[]): number => {
    // np.interp: clamp outside the range, linear inside.
    if (query <= xs[0]!) return ys[0]!;
    if (query >= xs[xs.length - 1]!) return ys[ys.length - 1]!;
    let k = 1;
    while (k < xs.length && xs[k]! < query) k++;
    const x0 = xs[k - 1]!, x1 = xs[k]!;
    const y0 = ys[k - 1]!, y1 = ys[k]!;
    if (x1 === x0) return y0;
    return y0 + ((query - x0) / (x1 - x0)) * (y1 - y0);
  };

  let totalScore = 0;
  let totalInterval = 0;
  for (let i = 0; i < n; i++) {
    const ix = interp(gt[i]!, pt, px);
    const iy = interp(gt[i]!, pt, py);
    const error = Math.hypot(gx[i]! - ix, gy[i]! - iy);
    const denom = Math.hypot(gx[i]!, gy[i]!) + eps;
    const normError = Math.min(1, error / denom);
    const w = Math.abs(interval[i]!);
    totalScore += (1 - normError) * w;
    totalInterval += w;
  }
  return totalInterval > 0 ? Math.min(1, totalScore / totalInterval) : 0;
}

/** Upstream `compare_continuous`: line-plot F1 of two directional interpolation recalls. */
export function compareContinuous(
  pred: Series,
  gt: Series,
): { f1: number; recall: number; precision: number } {
  let px = [...pred.x], py = [...pred.y];
  let gx = [...gt.x], gy = [...gt.y];
  const unique = (a: readonly number[]): number => new Set(a).size;
  if (unique(px) === 1 || unique(gx) === 1) {
    [px, py] = [py, px];
    [gx, gy] = [gy, gx];
  }
  // Upstream: (g_ys.max() - g_ys.min()) / 100 or 1e-5 — the range, parenthesised, then divided.
  const epsilon = (Math.max(...gy) - Math.min(...gy)) / 100 || EPS;
  const recall = arcLengthRecall(px, py, gx, gy, epsilon);
  const precision = arcLengthRecall(gx, gy, px, py, epsilon);
  const denom = precision + recall;
  const f1 = denom ? clamp01((2 * precision * recall) / denom) : 0;
  return { f1, recall, precision };
}

/** Upstream `_get_chart_types` + `calculate_chart_type_accuracy`: GT types must be a subset. */
export function CHART_TYPE_SETS(
  predTypes: readonly string[],
  gtTypes: readonly string[],
): boolean {
  const pred = new Set(predTypes);
  return gtTypes.every((t) => pred.has(t));
}

/** One score-engine assertion against an authoritative value. */
export interface SelfCheck {
  readonly name: string;
  readonly expected: number;
  readonly actual: number;
  readonly pass: boolean;
}

/** The whole offline report. No field here is a leaderboard number. */
export interface ScoreEngineReport {
  readonly engine: 'viscodebench-t2v_eval-replica';
  readonly source: string;
  readonly checks: readonly SelfCheck[];
  readonly llmCalls: number;
  readonly groundTruthRequired: boolean;
  readonly status: 'instrumented';
}

function check(name: string, expected: number, actual: number, tol: number): SelfCheck {
  return { name, expected, actual, pass: Math.abs(expected - actual) <= tol };
}

/**
 * Re-derive every oracle value from the ported functions. Runs offline; the self-check is the
 * evidence that the harness exists, which is what distinguishes `instrumented` from `absent`.
 */
export function scoreEngineSelfCheck(oracle: ScoreOracle): ScoreEngineReport {
  const checks: SelfCheck[] = [];
  const gs = oracle.getScore;
  checks.push(check('getScore/identity', gs.identity, getScore([[0, 0], [0, 0]]), 1e-8));
  checks.push(check('getScore/rect2x3', gs.rect2x3, getScore([[0.1, 0.9, 0.5], [0.8, 0.2, 0.4]]), 1e-8));
  checks.push(check('getScore/rect3x2', gs.rect3x2, getScore([[0.1, 0.9], [0.8, 0.2], [0.5, 0.4]]), 1e-8));
  checks.push(check('getScore/allMax', gs.allMax, getScore([[1, 1], [1, 1]]), 1e-8));
  checks.push(check('getScore/mixed', gs.mixed, getScore([[0.2, 0.7, 0.3], [0.6, 0.1, 0.8], [0.4, 0.5, 0.9]]), 1e-8));
  checks.push(check('getScore/oneZero', gs.oneZero, getScore([[0, 5], [5, 5]]), 1e-8));
  checks.push(check('scatter/identical', oracle.scatter.identical, compareScatter([[1, 2], [3, 4]], [[1, 2], [3, 4]]), 1e-8));
  checks.push(check('scatter/shifted', oracle.scatter.shifted, compareScatter([[1, 2], [3, 4]], [[10, 20], [30, 40]]), 1e-8));
  checks.push(check('discrete/identical', oracle.discrete.identical, compareDiscrete([10, 20, 30], [10, 20, 30]), 1e-8));
  checks.push(check('discrete/shifted', oracle.discrete.shifted, compareDiscrete([10, 20, 30], [100, 200, 300]), 1e-8));
  const p = { x: [0, 1, 2, 3], y: [0, 1, 4, 9] };
  checks.push(check('continuous/identical', oracle.continuous.identical!.f1, compareContinuous(p, p).f1, 1e-8));
  checks.push(check('continuous/shifted', oracle.continuous.shifted!.f1, compareContinuous(p, { x: [0, 1, 2, 3], y: [5, 6, 9, 14] }).f1, 1e-8));
  checks.push(check('continuous/scaled', oracle.continuous.scaled!.f1, compareContinuous(p, { x: [0, 1, 2, 3], y: [0, 2, 8, 18] }).f1, 1e-8));
  return {
    engine: 'viscodebench-t2v_eval-replica',
    source: 'https://github.com/SAIPLL/VisCodeBench/tree/main/t2v_eval/evaluation',
    checks,
    llmCalls: 0,
    groundTruthRequired: false,
    status: 'instrumented',
  };
}

/** Human-readable report; deliberately says "instrumented" and never prints a score as a reading. */
export function describeScoreEngine(report: ScoreEngineReport): string[] {
  const failed = report.checks.filter((c) => !c.pass);
  return [
    `viscodebench: score engine ${report.engine} (${report.status})`,
    `viscodebench: source ${report.source}`,
    `viscodebench: ${report.checks.length} oracle checks, ${failed.length} failed, ${report.llmCalls} LLM calls`,
    `viscodebench: the metric and harness exist but no dispatch has produced a number;`,
    `viscodebench: the primary score lives on the Codabench server against private references,`,
    `viscodebench: so this row is instrumented, not measured, and reports no leaderboard number.`,
  ];
}

/**
 * Run the self-check against the authority file. Kept separate from the guard so a test can drive
 * it with any oracle, including one whose numbers drift, and assert the exit code.
 */
export function runScoreEngine(
  oracle: ScoreOracle,
  log: (line: string) => void,
): number {
  const report = scoreEngineSelfCheck(oracle);
  for (const line of describeScoreEngine(report)) log(line);
  const failed = report.checks.filter((c) => !c.pass);
  for (const c of failed) log(`viscodebench: DRIFT ${c.name} expected ${c.expected} got ${c.actual}`);
  return failed.length === 0 ? 0 : 1;
}

/**
 * The command entry, written with the entry guard so importing the module in a test cannot start a
 * check and running it cannot be forgotten. Returns `undefined` when merely imported.
 */
export function entryScoreEngine(
  argv1: string | undefined,
  moduleUrl: string,
  log: (line: string) => void,
  readFile: (path: URL) => string,
): number | undefined {
  if (!isEntry(argv1, moduleUrl)) return undefined;
  try {
    const oracle = JSON.parse(readFile(new URL('./viscodebench-oracle.json', moduleUrl))) as ScoreOracle;
    return runScoreEngine(oracle, log);
  } catch (error) {
    log(`viscodebench: ${error instanceof Error ? error.message : String(error)}`);
    return 1;
  }
}

const entryCode = entryScoreEngine(
  process.argv[1],
  import.meta.url,
  (line) => process.stdout.write(`${line}\n`),
  (url) => readFileSync(url, 'utf-8'),
);
if (entryCode !== undefined) process.exitCode = entryCode;

