/**
 * The VisCodeBench end-to-end pilot: emit → log → parse → score, entirely offline.
 *
 * r212 (`viscodebench-score.ts`) ported the comparison half of upstream `t2v_eval`: given two
 * normalized figure-data dictionaries it computes Displayed Data Similarity. But the input contract
 * — the figure data `read_t2v_log_dir` produces from a `series.jsonl` — had no producer here, so the
 * generate → log → score loop was never closed in this repository and the comparator sat unwired.
 * This module is the missing half:
 *
 *   emitVisualisationCode  a structured chart spec -> Python with the upstream marker region,
 *                          executed by `viscodebench_log_worker.py` into a real `series.jsonl`.
 *   parseSeriesLog         upstream `series.jsonl` records -> normalized, grouped figure data
 *                          (min-max per axis, pie by proportion), exactly as `read_t2v_log_dir`
 *                          chains parse -> normalize -> group.
 *   compareSeries/Axes/Figures  the nested optimal assignment that wraps the r212 comparators
 *                          into one similarity, matching `compare_data_series` / `compare_axes` /
 *                          `compare_figures`.
 *   displayedDataSimilarity the whole loop, pinned to `viscodebench-pilot-oracle.json`, whose values
 *                          were produced by upstream `calculate_similarity_score` (scipy 1.17 /
 *                          numpy 2.3.5).
 *
 * Two facts are asserted rather than "fixed", because they are the metric's design and a future
 * reader will otherwise mistake them for bugs: (1) a shape-identical translate scores 1.0 because
 * min-max normalization erases location; (2) `accessibility` is absent because upstream needs OCR
 * and rendered pixels, which this offline harness deliberately does not fake.
 *
 * No model is called, no network is touched, no leaderboard number is claimed. The report status is
 * `instrumented`. The value of the loop is that a future dispatch scores through a path already
 * pinned to authority, at ¥0 per self-check.
 */

import { readFileSync } from 'node:fs';
import { isEntry } from '../entry.js';
import {
  CHART_TYPE_SETS,
  compareContinuous,
  compareDiscrete,
  compareScatter,
  getScore,
} from './viscodebench-score.js';

/** The four chart families this pilot can emit, execute and score. */
export const CHART_KINDS = ['line', 'scatter', 'bar', 'pie'] as const;
export type ChartKind = (typeof CHART_KINDS)[number];

/** A structured chart intent. `y` is required for line/scatter/bar and ignored for pie. */
export interface ChartSpec {
  readonly kind: ChartKind;
  readonly x: readonly number[];
  readonly y?: readonly number[];
  readonly label?: string;
}

/** One `data_series` entry inside an upstream `series.jsonl` record. */
export interface LogDataSeries {
  readonly x: readonly number[];
  readonly y?: readonly number[];
  readonly z?: readonly number[];
  readonly s?: readonly number[];
  readonly name?: string;
  readonly linestyle?: string;
}

/** One line of upstream `series.jsonl` (the compact format). */
export interface SeriesLogRecord {
  readonly axis_id: string;
  readonly plot_func_id: string;
  readonly plt_func: string;
  readonly data_series: readonly LogDataSeries[];
}

/** A normalized series — the value shape of `read_t2v_log_dir`'s fig_data. */
export interface FigSeries {
  readonly pltFunc: string;
  readonly data: {
    readonly x: readonly number[];
    readonly y?: readonly number[];
    readonly z?: readonly number[];
    readonly t?: readonly number[];
  };
  readonly name: string;
  readonly plotFuncId: string;
}

/** Figure data keyed by axis id, as `read_t2v_log_dir` returns. */
export type FigData = Readonly<Record<string, readonly FigSeries[]>>;

/** The authority file generated by upstream `calculate_similarity_score`. */
export interface PilotOracle {
  readonly note: string;
  readonly source: string;
  readonly command: string;
  readonly pairs: Readonly<Record<string, number>>;
}

/** A single self-check assertion. */
export interface PilotCheck {
  readonly name: string;
  readonly expected: number;
  readonly actual: number;
  readonly pass: boolean;
}

/** The whole offline report. No field here is a leaderboard number. */
export interface PilotReport {
  readonly engine: 'viscodebench-e2e-pilot';
  readonly status: 'instrumented';
  readonly llmCalls: number;
  readonly groundTruthRequired: boolean;
  readonly checks: readonly PilotCheck[];
  readonly chartTypeAccuracy: boolean;
}

const EPS = 1e-5;
const NON_PLOTTABLE = new Set(['axvline', 'axhline']);
/** Upstream `_PLT_FUNC_GROUP`: plot-like curves keep identity; everything else merges per axis. */
const PLOT_GROUP = new Set(['plot', 'fill_between', 'fill_betweenx', 'stem', 'stairs']);
const SCATTER_GROUP = new Set(['scatter', 'sns_plot_strips', 'sns_plot_swarms']);
const BAR_GROUP = new Set(['bar', 'barh', 'hist', 'errorbar']);

/** JSON-escape a label into a Python string literal without allowing a break-out. */
function pyString(value: string): string {
  return JSON.stringify(value);
}

/**
 * Emit a chart spec as Python with the exact upstream marker region. The worker executes only the
 * region, so the emitted code is the chart and nothing else.
 */
export function emitVisualisationCode(spec: ChartSpec): string {
  if (!CHART_KINDS.includes(spec.kind)) {
    throw new Error(`emitVisualisationCode: unsupported chart kind "${spec.kind}"`);
  }
  if (spec.x.length === 0) throw new Error('emitVisualisationCode: empty data');
  const all = spec.kind === 'pie' ? spec.x : [...spec.x, ...(spec.y ?? [])];
  if (all.some((v) => !Number.isFinite(v))) {
    throw new Error('emitVisualisationCode: non-finite coordinate');
  }
  if (spec.kind !== 'pie') {
    if (spec.y === undefined || spec.y.length !== spec.x.length) {
      throw new Error('emitVisualisationCode: x and y must have the same length');
    }
  }
  const xs = `[${spec.x.join(', ')}]`;
  let call: string;
  const label = spec.label === undefined ? '' : `, label=${pyString(spec.label)}`;
  if (spec.kind === 'pie') {
    call = `plt.pie(${xs}${label})`;
  } else {
    const ys = `[${spec.y!.join(', ')}]`;
    const fn = spec.kind === 'line' ? 'plot' : spec.kind;
    call = `plt.${fn}(${xs}, ${ys}${label})`;
  }
  return [
    '# emitted by nl2charts viscodebench-pilot',
    '##START VISUALISATION CODE',
    call,
    'plt.show()',
    '##END VISUALISATION CODE',
  ].join('\n');
}

const finite = (n: number): boolean => Number.isFinite(n);

/** Min-max normalize an array to [0,1]; a degenerate range is left unchanged (upstream `_scale`). */
export function minMax(arr: readonly number[], lo: number, hi: number): number[] {
  if (lo < hi && Number.isFinite(lo) && Number.isFinite(hi)) {
    return arr.map((v) => (v - lo) / (hi - lo));
  }
  return [...arr];
}

function groupOf(pltFunc: string): 'plot' | 'scatter' | 'bar' | 'pie' | string {
  if (PLOT_GROUP.has(pltFunc)) return 'plot';
  if (SCATTER_GROUP.has(pltFunc)) return 'scatter';
  if (BAR_GROUP.has(pltFunc)) return 'bar';
  if (pltFunc === 'pie') return 'pie';
  return pltFunc;
}

/**
 * Parse upstream `series.jsonl` records into normalized, grouped figure data. Chains the three
 * steps `read_t2v_log_dir` applies: parse (`_ingest_record` / `_parse_series`), normalize (min-max
 * across every series of an axis, pie by proportion), and group (same-type merge, plot kept apart).
 */
export function parseSeriesLog(records: readonly SeriesLogRecord[]): FigData {
  const byAxis = new Map<string, FigSeries[]>();
  for (const rec of records) {
    const pltFunc = rec.plt_func;
    for (const raw of rec.data_series) {
      if (NON_PLOTTABLE.has(pltFunc)) continue;
      const filteredX = raw.x.filter(finite);
      if (filteredX.length === 0) continue;
      let data: { x: number[]; y?: number[]; z?: number[]; t?: number[] };
      let actualFunc = pltFunc;
      if (pltFunc === 'pie') {
        data = { x: filteredX };
      } else if (SCATTER_GROUP.has(pltFunc)) {
        const rawZ = raw.z ?? raw.s ?? filteredX.map(() => 5);
        const n = Math.min(filteredX.length, (raw.y ?? filteredX).length, rawZ.length);
        data = {
          x: filteredX.slice(0, n),
          y: (raw.y ?? filteredX).slice(0, n),
          z: rawZ.slice(0, n),
        };
      } else {
        // plot / bar / barh / fill_between / ... : x and y parallel arrays.
        const ys = (raw.y ?? []).filter(finite);
        const n = Math.min(filteredX.length, ys.length);
        if (n === 0) continue;
        data = { x: filteredX.slice(0, n), y: ys.slice(0, n) };
        // Upstream reclassifies a linestyle-less plot as a scatter with z=5.
        if (pltFunc === 'plot' && (raw.linestyle === 'None' || raw.linestyle === undefined)) {
          actualFunc = 'scatter';
          data.z = filteredX.slice(0, n).map(() => 5);
        }
      }
      const axis = byAxis.get(rec.axis_id) ?? [];
      axis.push({ pltFunc: actualFunc, data, name: raw.name ?? '', plotFuncId: rec.plot_func_id });
      byAxis.set(rec.axis_id, axis);
    }
  }

  // Normalize across all series of an axis, matching upstream's shared min/max.
  const fig: Record<string, FigSeries[]> = {};
  for (const [axisId, series] of byAxis) {
    const keys = ['x', 'y', 'z', 't'] as const;
    const bounds = new Map<string, [number, number]>();
    for (const key of keys) {
      const values = series.flatMap((s) => (s.data[key] ?? []) as readonly number[]);
      if (values.length === 0) continue;
      let lo = Math.min(...values);
      let hi = Math.max(...values);
      if (lo === hi) hi += EPS;
      bounds.set(key, [lo, hi]);
    }
    const normalized = series.map((s) => {
      const data: { x: number[]; y?: number[]; z?: number[]; t?: number[] } = { x: [] };
      if (s.pltFunc === 'pie') {
        const total = s.data.x.reduce((a, b) => a + b, 0);
        data.x = total > 0 ? s.data.x.map((v) => v / total) : [...s.data.x];
      } else {
        for (const key of keys) {
          const arr = s.data[key];
          if (arr === undefined) continue;
          // bounds has an entry for every key present on any series of this axis.
          const b = bounds.get(key)!;
          (data as Record<string, number[]>)[key] = minMax(arr, b[0], b[1]);
        }
      }
      return { ...s, data };
    });
    // Group: plot curves stay separate; other families merge into one per axis.
    const grouped: FigSeries[] = [];
    const merged = new Map<string, FigSeries>();
    for (const s of normalized) {
      const group = groupOf(s.pltFunc);
      if (group === 'plot') {
        grouped.push({ ...s, pltFunc: 'plot' });
        continue;
      }
      const existing = merged.get(group);
      if (existing === undefined) {
        merged.set(group, { ...s, pltFunc: group, plotFuncId: `merged_${group}` });
      } else {
        const combined: FigSeries = {
          ...existing,
          data: {
            x: [...(existing.data.x as number[]), ...(s.data.x as number[])],
            y: [...((existing.data.y ?? []) as number[]), ...((s.data.y ?? []) as number[])],
            ...(existing.data.z !== undefined || s.data.z !== undefined
              ? { z: [...((existing.data.z ?? []) as number[]), ...((s.data.z ?? []) as number[])] }
              : {}),
          },
        };
        merged.set(group, combined);
      }
    }
    fig[axisId] = [...grouped, ...merged.values()];
  }
  return fig;
}

/**
 * Compare two series by plotting family, matching upstream `compare_data_series`: plot->plot uses
 * continuous F1, pie->pie uses the discrete comparator, everything else falls back to scatter.
 */
export function compareSeries(pred: FigSeries, gt: FigSeries): number {
  if (pred.pltFunc === 'plot' && gt.pltFunc === 'plot') {
    return compareContinuous(
      { x: pred.data.x as number[], y: (pred.data.y ?? []) as number[] },
      { x: gt.data.x as number[], y: (gt.data.y ?? []) as number[] },
    ).f1;
  }
  if (pred.pltFunc === 'pie' && gt.pltFunc === 'pie') {
    return compareDiscrete(pred.data.x as number[], gt.data.x as number[]);
  }
  const points = (s: FigSeries): readonly (readonly [number, number])[] =>
    (s.data.x as number[]).map((x, i) => [x, ((s.data.y ?? []) as number[])[i] ?? 0] as const);
  return compareScatter(points(pred), points(gt));
}

/**
 * Turn a similarity in [0,1] into an assignment cost. Upstream builds `1 - score_matrix`, first
 * replacing NaN with -1 (which becomes cost 1) and relying on the score itself being in [0,1]; the
 * clamp here makes an out-of-range comparator result harmless instead of a negative cost.
 */
export function simToCost(sim: number): number {
  if (Number.isNaN(sim)) return 1;
  return 1 - Math.max(0, Math.min(1, sim));
}

/** Upstream `compare_axes`: assign series optimally, score = getScore(1 - similarity matrix). */
export function compareAxes(
  pred: readonly FigSeries[],
  gt: readonly FigSeries[],
): number {
  if (pred.length === 0 || gt.length === 0) return 0;
  const cost = pred.map((p) => gt.map((g) => simToCost(compareSeries(p, g))));
  return getScore(cost);
}

/** Upstream `compare_figures`: assign axes optimally over the per-axis similarity matrix. */
export function compareFigures(pred: FigData, gt: FigData): number {
  const predAxes = Object.values(pred);
  const gtAxes = Object.values(gt);
  if (predAxes.length === 0 || gtAxes.length === 0) return 0;
  const cost = predAxes.map((p) => gtAxes.map((g) => simToCost(compareAxes(p, g))));
  return getScore(cost);
}

/**
 * End-to-end Displayed Data Similarity over two upstream `series.jsonl` logs.
 */
export function displayedDataSimilarity(
  predLog: readonly SeriesLogRecord[],
  gtLog: readonly SeriesLogRecord[],
): number {
  if (predLog.length === 0) throw new Error('displayedDataSimilarity: empty prediction log');
  if (gtLog.length === 0) throw new Error('displayedDataSimilarity: empty ground-truth log');
  return compareFigures(parseSeriesLog(predLog), parseSeriesLog(gtLog));
}

/** Run the oracle pairs. `logOf` injects the real fixture records by sample key. */
export function pilotSelfCheck(
  oracle: PilotOracle,
  logOf: (key: string) => readonly SeriesLogRecord[],
): PilotReport {
  const checks: PilotCheck[] = [];
  for (const [pair, expected] of Object.entries(oracle.pairs)) {
    const [pred, gt] = pair.split('|') as [string, string];
    const actual = displayedDataSimilarity(logOf(pred), logOf(gt));
    checks.push({ name: pair, expected, actual, pass: Math.abs(expected - actual) <= 1e-6 });
  }
  const gtTypes = ['line', 'scatter', 'bar', 'pie'];
  return {
    engine: 'viscodebench-e2e-pilot',
    status: 'instrumented',
    llmCalls: 0,
    groundTruthRequired: false,
    checks,
    chartTypeAccuracy: CHART_TYPE_SETS(gtTypes, gtTypes),
  };
}

/** Human-readable report; deliberately never prints a leaderboard number. */
export function describePilot(report: PilotReport): string[] {
  const failed = report.checks.filter((c) => !c.pass);
  return [
    `viscodebench-pilot: emit -> log -> parse -> score (${report.status})`,
    `viscodebench-pilot: ${report.checks.length} authority pairs, ${failed.length} failed, ${report.llmCalls} LLM calls`,
    `viscodebench-pilot: chart-type contract ${report.chartTypeAccuracy ? 'ok' : 'FAILED'}; ground truth required: ${report.groundTruthRequired}`,
    `viscodebench-pilot: the loop is pinned to upstream t2v_eval but the score still lives on Codabench;`,
    `viscodebench-pilot: this is an instrumented self-check, not a measured leaderboard reading.`,
  ];
}

/** Exit code 0 iff every authority pair passes. */
export function runPilot(
  oracle: PilotOracle,
  logOf: (key: string) => readonly SeriesLogRecord[],
  log: (line: string) => void,
): number {
  const report = pilotSelfCheck(oracle, logOf);
  for (const line of describePilot(report)) log(line);
  for (const c of report.checks.filter((x) => !x.pass)) {
    log(`viscodebench-pilot: DRIFT ${c.name} expected ${c.expected} got ${c.actual}`);
  }
  return report.checks.every((c) => c.pass) ? 0 : 1;
}

/**
 * CLI entry. `readOracle` and `logOf` are injected so a test can drive both the entry and import
 * paths. `moduleUrl` is passed explicitly so `isEntry` can be exercised; the real launcher supplies
 * `import.meta.url`.
 */
export function entryPilot(
  argv1: string | undefined,
  moduleUrl: string,
  log: (line: string) => void,
  readOracle: () => PilotOracle,
  logOf: (key: string) => readonly SeriesLogRecord[],
  entryUrl: string = moduleUrl,
): number | undefined {
  if (!isEntry(argv1, entryUrl)) return undefined;
  try {
    return runPilot(readOracle(), logOf, log);
  } catch (error) {
    log(`viscodebench-pilot: ${error instanceof Error ? error.message : String(error)}`);
    return 1;
  }
}

/** A lazy fixture reader: the file is touched only when a log is actually requested. */
export function realLogOf(key: string): readonly SeriesLogRecord[] {
  const fx = JSON.parse(
    readFileSync(new URL('./viscodebench-pilot-fixture.json', import.meta.url), 'utf-8'),
  ) as { samples: Record<string, { series: SeriesLogRecord[] }> };
  const sample = fx.samples[key];
  if (sample === undefined) throw new Error(`unknown fixture sample "${key}"`);
  return sample.series;
}

const entryCode = entryPilot(
  process.argv[1],
  import.meta.url,
  (line) => process.stdout.write(`${line}\n`),
  () => JSON.parse(
    readFileSync(new URL('./viscodebench-pilot-oracle.json', import.meta.url), 'utf-8'),
  ) as PilotOracle,
  realLogOf,
);
if (entryCode !== undefined) process.exitCode = entryCode;
